import { Agent } from "@openai/agents";

// Ревью по чек-листу с готовым JSON-ответом проще генерации плана, поэтому
// ревьюер сидит на flash (примерно в 20 раз дешевле pro).
const REVIEWER_MODEL = process.env.OPENROUTER_REVIEWER_MODEL ?? "deepseek/deepseek-v4-flash-0731";

// ─────────────────────────────────────────────────────────────────────────────
// У РЕВЬЮЕРА НЕТ TOOLS — И НЕ ДОЛЖНО ПОЯВИТЬСЯ
//
// Ревьюер — контролирующая сторона, и единственное, что он делает, — выносит
// вердикт по тексту, который ему дали. Никаких побочных эффектов: он не читает
// файлы сам, не пишет на диск, не вызывает скиллы. Причины:
//
// 1. Проверяемость. Вердикт должен быть функцией входа. Дай ревьюеру инструменты
//    чтения — и один и тот же план начнёт получать разные вердикты в зависимости
//    от того, что модель решила подтянуть в этот раз.
// 2. Разделение ролей. Сторона, которая одобряет запись на диск, не может сама
//    на диск писать: иначе гейт «сохраняем только одобренное» теряет смысл.
// 3. Стоимость ошибки. Коуч с кривым tool-call просто потратит лишний оборот;
//    ревьюер с правом записи может затереть результат прогона.
//
// Поэтому поле tools здесь не задано и задаваться не должно: весь вход приходит
// текстом от харнесса, весь выход — JSON по схеме из harness/validateReview.ts.
//
// Промпт приходит параметром (версию выбирает харнесс). Здесь остаётся только
// конфигурация агента.
// ─────────────────────────────────────────────────────────────────────────────
export function createSafetyReviewer(instructions: string): Agent {
  return new Agent({ name: "Safety Reviewer", instructions, model: REVIEWER_MODEL });
}
