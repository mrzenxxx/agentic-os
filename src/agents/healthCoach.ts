import { Agent, type Tool } from "@openai/agents";

// Модель в формате OpenRouter: "<вендор>/<модель>". Генерация плана — задача
// сложнее ревью по чек-листу, поэтому коуч сидит на pro.
// Список актуальных id: https://openrouter.ai/api/v1/models
const COACH_MODEL = process.env.OPENROUTER_COACH_MODEL ?? "deepseek/deepseek-v4-pro-0813";

// ─────────────────────────────────────────────────────────────────────────────
// new Agent({...}) — это не сетевой вызов и не процесс, а конфигурация одного
// «участника»: кто он, что ему сказано в системном промпте, какой моделью он
// думает и что ему разрешено вызывать. Объект неизменяемый и переиспользуемый:
// один и тот же агент можно гонять сколько угодно раз с разным входом.
//   name         — метка агента (логи, трейсы, передача управления между агентами)
//   instructions — системный промпт: уходит первым сообщением с role: "system"
//   model        — строка-id; резолвится через клиент из setDefaultOpenAIClient
//                  (его ставит харнесс перед первым прогоном)
//   tools        — инструменты, которые модель видит в этом прогоне и может вызвать
//
// Промпт и набор tools приходят параметрами, а не живут здесь: какую версию
// промпта взять и какие инструменты открыть на этой фазе, решает харнесс
// (см. promptVersions.ts и skills/index.ts). Этот модуль отвечает только за то,
// кем агент является и на какой модели работает.
//
// toolChoice="required" нужен фазе сохранения: там от агента ждут не текста, а
// ровно одного вызова инструмента. Бесконечного цикла из этого не выходит —
// resetToolChoice в SDK по умолчанию true и возвращает выбор в "auto" сразу
// после первого вызова.
// ─────────────────────────────────────────────────────────────────────────────
export function createHealthCoach(
  instructions: string,
  tools: Tool[] = [],
  toolChoice: "auto" | "required" = "auto",
): Agent {
  return new Agent({
    name: "Health Coach",
    instructions,
    model: COACH_MODEL,
    tools,
    modelSettings: { toolChoice },
  });
}
