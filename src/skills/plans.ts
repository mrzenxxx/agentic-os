import { tool } from "@openai/agents";
import { z } from "zod";

import { writeDataFile } from "./dataFile";

/**
 * Скилл «сохранить план»: единственная запись, ради которой прогон вообще
 * существует. Поэтому у него особый режим доступа — см. комментарий у tool'а.
 */

export type SavePlanResult = { ok: true; path: string; chars: number };

/** Чистая функция скилла: пишет план в data/output.md поверх прошлого. */
export function savePlan(markdown: string): SavePlanResult {
  const content = markdown.trim();
  const path = writeDataFile("output.md", `${content}\n`);
  return { ok: true, path, chars: content.length };
}

// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ДОСТУП К ЭТОМУ TOOL'У ГЕЙТИТ ХАРНЕСС, А НЕ ПРОМПТ
//
// Правило «сохраняй план только после approve ревьюера» можно написать в
// промпте — и оно будет соблюдаться ровно до первого прогона, где модель решит
// иначе. Инструкция в промпте — это просьба, её вес зависит от модели,
// температуры и длины контекста; проверить её постфактум нельзя, потому что
// файл на диске уже перезаписан.
//
// Единственное место, где запрет можно сделать физическим, — список tools
// агента. На раундах генерации харнесс собирает коуча БЕЗ savePlanTool: модель
// не может вызвать то, чего ей не показали, сколько бы её ни уговаривали в
// задаче пользователя. После approve харнесс поднимает коуча второй
// конфигурацией, где savePlanTool единственный инструмент.
//
// Так инвариант «на диск попадает только одобренный план» держится кодом, а не
// текстом, и ломается только правкой харнесса — которая видна в диффе.
// См. runHealthAgent.ts, фазу сохранения.
// ─────────────────────────────────────────────────────────────────────────────
export const savePlanTool = tool({
  name: "savePlan",
  description:
    "Сохраняет финальный план в data/output.md, перезаписывая прошлый. Передавай план " +
    "целиком и дословно, в markdown, без сокращений и без комментариев от себя: в файл " +
    "попадёт ровно то, что ты передашь. Инструмент доступен только после того, как " +
    "Safety Reviewer одобрил план, поэтому вызывать его можно без дополнительных проверок.",
  parameters: z.object({
    markdown: z
      .string()
      .min(1)
      .describe("Полный текст одобренного плана в markdown — то, что увидит пользователь в файле."),
  }),
  execute: async ({ markdown }) => savePlan(markdown),
});
