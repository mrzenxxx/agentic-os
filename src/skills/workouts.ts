import { tool } from "@openai/agents";
import { z } from "zod";

/**
 * Скилл «шаблон тренировки»: заготовки схем под типовые цели.
 *
 * Шаблоны захардкожены намеренно. Это не база данных и не справочник упражнений,
 * а каркас: структура недели, объём и прогрессия — то, что модель без опоры
 * придумывает каждый раз заново и по-разному. Подбор упражнений под ограничения
 * профиля остаётся за коучем, скилл в профиль не смотрит.
 */

export const WORKOUT_GOALS = ["mass_gain", "return_to_training", "endurance", "mobility"] as const;
export type WorkoutGoal = (typeof WORKOUT_GOALS)[number];

const TEMPLATES: Record<WorkoutGoal, string> = {
  mass_gain: `## Шаблон: набор мышечной массы
- Частота: 3 силовые в неделю (пн / ср / пт), между ними день отдыха
- Структура занятия: разминка 10 мин → 5 базовых упражнений → заминка 5 мин
- Объём: 3–4 подхода по 6–10 повторений, отдых 2–3 мин между подходами
- Прогрессия: +2,5 кг к рабочему весу, когда все подходы закрыты в верхней границе повторений
- День A: жим лёжа, тяга в наклоне, жим ногами, подъём на бицепс, планка
- День B: приседания, тяга верхнего блока, жим стоя, разгибание на трицепс, гиперэкстензия
- Кардио: 2 прогулки по 30–40 мин в дни отдыха, не вместо силовой
- Условие роста: профицит калорий и 7–8 часов сна, иначе объём только выжигает ресурс`,

  return_to_training: `## Шаблон: возвращение после долгого перерыва
- Частота: 2 занятия в неделю первые 3 недели, с 4-й недели — 3
- Первые 2 недели: только тренажёры и собственный вес, без свободных весов
- Объём: 2 подхода по 12–15 повторений, вес — чтобы в запасе оставалось 4–5 повторений
- Занятие целиком: 35–40 мин, из них 10 мин разминка
- Круг: жим ногами, тяга верхнего блока, жим в тренажёре, сгибание голени, планка 3×30 с
- Правило недели: если после занятия мышцы болят дольше 48 часов — следующий объём не растёт
- Кардио: ходьба 20–30 мин в свободные дни, пульс разговорный`,

  endurance: `## Шаблон: общая выносливость
- Частота: 4 занятия в неделю — 3 кардио + 1 силовое на всё тело
- Кардио 1 (длинное): 45–60 мин в разговорном темпе
- Кардио 2 (темповое): 25 мин ровного темпа чуть выше комфортного
- Кардио 3 (интервалы): 8 × (1 мин быстро / 2 мин спокойно) + разминка и заминка по 10 мин
- Силовое: 5 упражнений, 2–3 подхода по 12–15 повторений, круговым форматом
- Прогрессия: +5 мин к длинному кардио каждую неделю, не больше
- Контроль: утренний пульс вырос на 8–10 ударов — неделя идёт в разгрузку`,

  mobility: `## Шаблон: подвижность и восстановление для сидячей работы
- Частота: ежедневно 15 мин + 2 полноценных занятия по 30 мин в неделю
- Ежедневный минимум: разгрузка шеи и грудного отдела, раскрытие тазобедренных, дыхание 2 мин
- Занятие: 6–8 упражнений, по 2 подхода, удержание позы 30–45 с, без боли
- Блок 1 (грудной отдел и плечи): вращения лопатками, растяжка груди в проёме, «кошка-корова»
- Блок 2 (таз и ноги): выпад с раскрытием, растяжка задней поверхности бедра, ягодичный мостик
- Перерывы в работе: вставать каждые 50 мин на 3–5 мин, иначе дневной эффект съедается
- Прогрессия: не в амплитуде, а в регулярности — сначала 7 дней подряд, потом объём`,
};

/** Чистая функция скилла: цель → markdown-шаблон. */
export function suggestWorkoutTemplate(goal: WorkoutGoal): string {
  return TEMPLATES[goal];
}

export const suggestWorkoutTemplateTool = tool({
  name: "suggestWorkoutTemplate",
  description:
    "Возвращает готовый каркас тренировочной недели под одну из четырёх целей: частота, " +
    "структура занятия, объём, прогрессия и условия, при которых нагрузку не повышают. " +
    "Вызывай перед составлением плана тренировок, чтобы не изобретать схему с нуля. " +
    "Шаблон — это основа, а не ответ: упражнения под ограничения и опыт пользователя " +
    "подбирай сам, сверившись с getProfile и getRecentLog. Шаблон про профиль ничего не знает.",
  parameters: z.object({
    goal: z
      .enum(WORKOUT_GOALS)
      .describe(
        "Цель недели: mass_gain — набор мышечной массы для тренирующегося; " +
          "return_to_training — старт после долгого перерыва или с нуля; " +
          "endurance — общая выносливость и кардио; " +
          "mobility — подвижность и восстановление при сидячей работе.",
      ),
  }),
  execute: async ({ goal }) => suggestWorkoutTemplate(goal),
});
