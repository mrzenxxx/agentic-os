import { tool } from "@openai/agents";
import { z } from "zod";

import { readDataFile } from "./dataFile";

/**
 * Скилл «профиль пользователя»: постоянные данные — цели, ограничения,
 * предпочтения, текущий режим. Меняются редко, в отличие от дневника.
 */

const EMPTY = "Профиль пуст: data/profile.md не заполнен.";

/** Чистая функция скилла — её же можно звать из харнесса мимо модели. */
export function getProfile(): string {
  return readDataFile("profile.md", EMPTY);
}

// Описание tool'а — это интерфейс для модели: по нему она решает, звать ли
// инструмент. Поэтому здесь сказано не только «что отдаёт», но и «когда нужен»
// и «чего в нём нет», иначе модель тянет профиль на каждый запрос подряд.
export const getProfileTool = tool({
  name: "getProfile",
  description:
    "Возвращает профиль пользователя в markdown: возраст, рост и вес, характер работы, " +
    "цели, ограничения по еде и нагрузке, предпочтения, текущий уровень тренированности. " +
    "Вызывай перед любым планом питания, тренировок или режима — без профиля план " +
    "рискует нарушить ограничения пользователя. Профиль статичен: он не содержит " +
    "записей о последних днях, для них есть getRecentLog.",
  parameters: z.object({}),
  execute: async () => getProfile(),
});
